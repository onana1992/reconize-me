const FALLBACK: Record<string, Record<string, string>> = {
  XK: { fr: "Kosovo", en: "Kosovo" },
};

export type Country = { code: string; name: string };

const cache = new Map<string, Country[]>();

export function countries(locale: string): Country[] {
  const hit = cache.get(locale);
  if (hit) {
    return hit;
  }
  const display = new Intl.DisplayNames([locale], { type: "region" });
  const language = locale.split("-")[0] ?? locale;
  const list = CODES.map((code) => {
    const named = display.of(code);
    const name = named && named !== code ? named : (FALLBACK[code]?.[language] ?? code);
    return { code, name };
  });
  list.sort((a, b) => a.name.localeCompare(b.name, locale));
  cache.set(locale, list);
  return list;
}

export function countryLabel(locale: string, code: string | null | undefined): string | null {
  if (!code) {
    return null;
  }
  const normalized = code.trim().toUpperCase();
  return countries(locale).find((item) => item.code === normalized)?.name ?? normalized;
}
